#!/usr/bin/env python3
"""Generate the spoken-Welsh prebuilt wordlist for the AnySoftKeyboard Welsh pack.

The pack dictionary is built from a Welsh Wikipedia sample whose frequencies
are scaled linearly (top word = 64), which squashes the living vocabulary
into f=1..10 and leaves spoken-register forms (mutations after fy/dy/ei,
contractions) missing or buried. This script emits a prebuilt wordlist XML
(hand-set frequencies, merged with MAX semantics by the ASK build) that
lifts the spoken layer: core contractions, everyday words, and the full
mutation paradigms of common nouns, generated by the deterministic Welsh
mutation rules.

Output: pack/dictionary/prebuilt/welsh_spoken.xml  (run from the welsh addon dir)
"""
import sys
import xml.sax.saxutils as x

# ---------- mutation rules (initial letter) ----------
# soft (treiglad meddal): p>b t>d c>g b>f d>dd g>drop m>f ll>l rh>r
SOFT = {"p": "b", "t": "d", "c": "g", "b": "f", "d": "dd", "g": "", "m": "f"}
# nasal (treiglad trwynol): p>mh t>nh c>ngh b>m d>n g>ng
NASAL = {"p": "mh", "t": "nh", "c": "ngh", "b": "m", "d": "n", "g": "ng"}
# aspirate (treiglad llaes): p>ph t>th c>ch
ASPIRATE = {"p": "ph", "t": "th", "c": "ch"}


def mutate(word, table):
    """Return the mutated form of `word` under `table`, or None if it does not mutate."""
    lower = word.lower()
    if lower.startswith("ll"):
        return "l" + word[2:] if "ll" in table.get("_digraphs", {}) else None
    if lower.startswith("rh"):
        return "r" + word[2:] if "rh" in table.get("_digraphs", {}) else None
    first = lower[0]
    if first in table:
        return table[first] + word[1:]
    return None


SOFT["_digraphs"] = {"ll": "l", "rh": "r"}


def cap_first(s):
    return s[:1].upper() + s[1:] if s else s


entries = {}  # word -> freq (keep max if generated twice)


def add(word, freq):
    if word and entries.get(word, 0) < freq:
        entries[word] = freq


# ---------- core spoken forms: contractions, function words ----------
CORE = {
    "dwi'n": 255, "mae'n": 248, "rwy'n": 244, "dwi": 246, "dw": 200,
    "rydw": 210, "rwy": 205, "mae": 250, "oedd": 235, "roedd": 238,
    "bydd": 232, "fydd": 218, "oes": 240, "does": 242, "ydy": 226,
    "yw": 228, "dydy": 224, "dwyt": 214, "wyt": 222, "rydych": 216,
    "ydych": 216, "ydyn": 214, "rydyn": 212, "eisiau": 244, "isio": 190,
    "angen": 236, "gallu": 228, "gallaf": 206, "hoffwn": 204, "hoffai": 196,
    "diolch": 250, "croeso": 246, "hwyl": 236, "bore": 240, "noswaith": 238,
    "nos": 234, "dydd": 234, "heddiw": 242, "yfory": 232, "ddoe": 230,
    "rwan": 208, "nawr": 226, "yma": 238, "yna": 236, "ac": 240,
    "hefyd": 234, "iawn": 246, "fawr": 244, "fach": 226, "dda": 222,
    "ddrwg": 208, "gyflym": 206, "brydferth": 198, "gryf": 200,
    "gynnes": 202, "boeth": 204, "bell": 206, "fyr": 200, "denau": 196,
    "drwm": 198, "dlawd": 192, "drist": 206, "mawr": 246, "bach": 240,
    "da": 248, "drwg": 224, "hen": 238, "newydd": 234, "ifanc": 226,
    "prydferth": 214, "cryf": 216, "gwan": 208, "cyflym": 220,
    "araf": 214, "hawdd": 222, "anodd": 224, "poeth": 218, "oer": 228,
    "cynnes": 220, "gwlyb": 210, "sych": 216, "glân": 222, "budr": 204,
    "llawn": 228, "gwag": 214, "agos": 224, "pell": 216, "uchel": 216,
    "isel": 212, "hir": 230, "byr": 220, "tew": 208, "tenau": 210,
    "trwm": 212, "ysgafn": 204, "cyfoethog": 200, "tlawd": 204,
    "hapus": 230, "trist": 222, "blin": 214, "llwglyd": 200,
}
for w, f in CORE.items():
    add(w, f)

# ---------- common nouns: full mutation paradigms ----------
NOUNS = [
    "cath", "ci", "tŷ", "afon", "bwrdd", "cadair", "drws", "ffenestr",
    "car", "bws", "trên", "llyfr", "papur", "arian", "dŵr", "bara",
    "caws", "llaeth", "coffi", "te", "cig", "afal", "oren", "ysgol",
    "gwaith", "cartref", "gwlad", "dinas", "pentref", "môr", "mynydd",
    "coeden", "blodyn", "haul", "lleuad", "seren", "glaw", "eira",
    "gwynt", "tân", "plentyn", "dyn", "menyw", "bachgen", "merch",
    "babi", "mam", "tad", "brawd", "chwaer", "ffrind", "athro",
    "meddyg", "gardd", "cae", "ffordd", "stryd", "pont", "castell",
    "eglwys", "siop", "marchnad", "banc", "gwesty", "bwyty", "parc",
    "traeth", "ynys", "llyn", "ceffyl", "buwch", "dafad", "mochyn",
    "aderyn", "pysgod", "desg", "ffôn", "teledu", "radio", "stori",
    "cân", "llun", "beic", "awyren", "bag", "het", "cot", "crys",
    "esgidiau", "sbectol", "bwyd", "diod", "gwin", "cwrw", "menyn",
    "wy", "tatws", "moron", "halen", "siwgr", "blawd", "reis",
    "cawl", "cacen", "siocled", "teulu", "pen", "llaw", "troed",
    "llygad", "clust", "trwyn", "ceg", "gwddf", "bola", "cefn",
    "bys", "garddwrn", "allwedd", "drws",
]
F_BASE, F_SOFT, F_NASAL, F_ASP = 205, 185, 170, 150
for noun in dict.fromkeys(NOUNS):  # dedupe, keep order
    add(noun, F_BASE)
    s = mutate(noun, SOFT)
    if s:
        add(s, F_SOFT)
    n = mutate(noun, NASAL)
    if n:
        add(n, F_NASAL)
    a = mutate(noun, ASPIRATE)
    if a:
        add(a, F_ASP)

# ---------- place names: base + soft + nasal (capitalised) ----------
PLACES = [
    "Cymru", "Caerdydd", "Caerfyrddin", "Casnewydd", "Caernarfon",
    "Conwy", "Caergybi", "Bangor", "Pwllheli", "Aberystwyth",
    "Abertawe", "Wrecsam", "Llanelli", "Merthyr", "Penarth",
    "Dinbych", "Bala", "Dolgellau", "Machynlleth", "Tywyn",
]
for place in PLACES:
    add(place, 215)
    s = mutate(place, SOFT)
    if s:
        add(cap_first(s), 175)
    n = mutate(place, NASAL)
    if n:
        add(cap_first(n), 190)

# ---------- everyday verbs (base forms present and strong) ----------
VERBS = [
    "mynd", "dod", "gwneud", "cael", "gweld", "clywed", "siarad",
    "bwyta", "yfed", "darllen", "ysgrifennu", "chwarae", "gweithio",
    "byw", "cysgu", "codi", "eistedd", "sefyll", "rhedeg", "cerdded",
    "nofio", "canu", "dawnsio", "coginio", "prynu", "gwerthu", "agor",
    "cau", "dechrau", "gorffen", "helpu", "cofio", "anghofio",
    "gwybod", "deall", "credu", "meddwl", "teimlo", "caru", "crio",
    "chwerthin", "edrych", "gwrando", "aros", "dysgu", "cyrraedd",
]
for v in VERBS:
    add(v, 215)

# ---------- emit ----------
out = ['<?xml version="1.0" encoding="UTF-8" ?>', "<wordlist>"]
for word in sorted(entries, key=lambda w: (-entries[w], w)):
    out.append(f'<w f="{entries[word]}">{x.escape(word)}</w>')
out.append("</wordlist>")

path = sys.argv[1] if len(sys.argv) > 1 else "welsh_spoken.xml"
with open(path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print(f"wrote {path}: {len(entries)} entries")
for probe in ("dwi'n", "nghath", "gath", "chath", "fawr", "Nghymru",
              "Mangor", "Gaerdydd", "waith", "ngwaith", "ardd"):
    print(f"  {probe}: f={entries.get(probe)}")
